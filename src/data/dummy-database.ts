// Generate additional transactions for better analytics
const generateAdditionalTransactions = (customers: any[], products: any[]) => {
  const transactions = [];
  const paymentMethods = ["Cash", "Card", "UPI"];

  // Generate 15 more transactions spread over the last 30 days
  for (let i = 0; i < 15; i++) {
    const randomCustomer =
      customers[Math.floor(Math.random() * customers.length)];
    const randomProduct = products[Math.floor(Math.random() * products.length)];
    const quantity = Math.floor(Math.random() * 5) + 1;
    const paymentMethod =
      paymentMethods[Math.floor(Math.random() * paymentMethods.length)];

    // Random date in the last 30 days
    const date = new Date();
    date.setDate(date.getDate() - Math.floor(Math.random() * 30));

    const subtotal = randomProduct.price * quantity;
    const discount = Math.random() > 0.8 ? Math.floor(subtotal * 0.1) : 0;
    const taxAmount = Math.floor(
      (subtotal - discount) * (randomProduct.taxRate / 100)
    );
    const total = subtotal - discount + taxAmount;

    transactions.push({
      id: generateId(),
      invoiceNumber: `INV-2024-${String(26 + i).padStart(3, "0")}`,
      date,
      customer: randomCustomer.id,
      amount: total,
      paymentMethod,
      status: "completed",
      items: [
        {
          id: randomProduct.id,
          name: randomProduct.name,
          price: randomProduct.price,
          quantity,
        },
      ],
      subtotal,
      discount,
      taxAmount,
      amountReceived:
        paymentMethod === "Cash"
          ? total + Math.floor(Math.random() * 100)
          : total,
      change: paymentMethod === "Cash" ? Math.floor(Math.random() * 100) : 0,
      createdAt: date,
    });
  }

  return transactions;
};
