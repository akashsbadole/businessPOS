import {
  ProductService,
  CustomerService,
  CategoryService,
  SupplierService,
  InvoiceService,
} from "../services/database-factory";

export const loadDummyData = async () => {
  try {
    console.log("🔄 Loading dummy data into database...");

    // Check if data already exists
    const existingProducts = await ProductService.getAll();
    const existingCustomers = await CustomerService.getAll();

    if (existingProducts.length > 0 || existingCustomers.length > 0) {
      console.log(
        "📊 Database already contains data, skipping dummy data load"
      );
      return {
        success: true,
        message: "Database already populated",
        counts: {
          products: existingProducts.length,
          customers: existingCustomers.length,
          categories: 0,
          suppliers: 0,
          transactions: 0,
        },
      };
    }

    let loadedCounts = {
      categories: 0,
      suppliers: 0,
      products: 0,
      customers: 0,
      transactions: 0,
    };

    // Load Categories
    console.log("📂 Loading categories...");
    for (const category of dummyCategories) {
      try {
        await CategoryService.create(category);
        loadedCounts.categories++;
      } catch (error) {
        console.warn("⚠️ Failed to create category:", category.name, error);
      }
    }

    // Load Suppliers
    console.log("🏢 Loading suppliers...");
    for (const supplier of dummySuppliers) {
      try {
        await SupplierService.create(supplier);
        loadedCounts.suppliers++;
      } catch (error) {
        console.warn("⚠️ Failed to create supplier:", supplier.name, error);
      }
    }

    // Load Products
    console.log("🛍️ Loading products...");
    for (const product of dummyProducts) {
      try {
        await ProductService.create(product);
        loadedCounts.products++;
      } catch (error) {
        console.warn("⚠️ Failed to create product:", product.name, error);
      }
    }

    // Load Customers
    console.log("👥 Loading customers...");
    for (const customer of dummyCustomers) {
      try {
        await CustomerService.create(customer);
        loadedCounts.customers++;
      } catch (error) {
        console.warn("⚠️ Failed to create customer:", customer.name, error);
      }
    }

    // Load Transactions
    console.log("📋 Loading transactions...");
    for (const transaction of dummyTransactions) {
      try {
        await InvoiceService.create(transaction);
        loadedCounts.transactions++;
      } catch (error) {
        console.warn(
          "⚠️ Failed to create transaction:",
          transaction.invoiceNumber,
          error
        );
      }
    }

    console.log("✅ Dummy data loaded successfully!");
    console.log("📊 Loaded counts:", loadedCounts);

    return {
      success: true,
      message: "Dummy data loaded successfully",
      counts: loadedCounts,
    };
  } catch (error) {
    console.error("❌ Failed to load dummy data:", error);
    return {
      success: false,
      message: "Failed to load dummy data",
      error: error.message,
      counts: {
        categories: 0,
        suppliers: 0,
        products: 0,
        customers: 0,
        transactions: 0,
      },
    };
  }
};

